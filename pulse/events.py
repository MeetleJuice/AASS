"""Durable bounded metadata stream. Free-form text is excluded at the boundary."""

import hashlib
import json
import math
import re
import time
from datetime import datetime, timezone
from pathlib import Path

SCHEMA_VERSION = 1
IDENTIFIERS = {
    "test_id",
    "component",
    "event_type",
    "action",
    "outcome",
    "error_category",
    "mode",
    "provider",
    "schema_version",
    "action_type",
    "field",
}
NUMBERS = {
    "step",
    "duration",
    "reserved_tokens",
    "remaining_tokens",
    "actual_input_tokens",
    "actual_output_tokens",
    "request_count",
    "retry",
    "strategy",
    "returncode",
    "writes_without_test",
    "first_test_seconds",
    "budget_before_test",
}
FLAGS = {"feedback_delivered", "recovered", "reported_usage", "automatic", "repeated_content"}
HASHES = {"artifact_hash", "snapshot_hash", "model_hash", "related_event_id"}


def metadata(data):
    """Unknown fields and arbitrary values never reach disk, UI or ZIP exports."""
    safe = {}
    for key, value in data.items():
        if key == "fields" and isinstance(value, list):
            safe[key] = [
                name
                for name in value
                if name
                in {"path", "content", "command", "reason", "operation", "tool", "arguments"}
            ][:10]
            continue
        if (
            key in IDENTIFIERS
            and isinstance(value, str)
            and re.fullmatch(r"[a-z][a-z0-9_.-]{0,63}", value)
        ):
            # These identifiers are generated by trusted harness code, not model text.
            safe[key] = value
        elif key in NUMBERS and type(value) in (int, float) and math.isfinite(value):
            safe[key] = value
        elif key in FLAGS and type(value) is bool:
            safe[key] = value
        elif key in HASHES and isinstance(value, str) and re.fullmatch(r"[0-9a-f]{16,64}", value):
            safe[key] = value
    return safe


def digest(value):
    return hashlib.sha256(str(value).encode()).hexdigest()


class EventStream:
    def __init__(self, directory, run_id, *, max_bytes=2 * 1024 * 1024, callback=None):
        self.directory = Path(directory)
        from settings import is_link

        if is_link(self.directory):
            raise ValueError("Diagnostic directory cannot be a link")
        self.directory.mkdir(parents=True, exist_ok=True)
        self.path = self.directory / "events.jsonl"
        if is_link(self.path) or (self.path.exists() and self.path.stat().st_nlink > 1):
            raise ValueError("Diagnostic events cannot be linked")
        self.run_id = run_id
        self.started = time.monotonic()
        self.sequence = 0
        self.max_bytes = max_bytes
        self.truncated = False
        self.callback = callback

    def emit(self, **data):
        if self.truncated:
            return None
        self.sequence += 1
        event = {
            "schema": SCHEMA_VERSION,
            "run_id": self.run_id,
            "sequence": self.sequence,
            "event_id": digest(f"{self.run_id}:{self.sequence}")[:24],
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "elapsed": round(time.monotonic() - self.started, 4),
            **metadata(data),
        }
        encoded = (json.dumps(event, sort_keys=True) + "\n").encode()
        if self.path.exists() and self.path.stat().st_size + len(encoded) > self.max_bytes:
            self.truncated = True
            # A separate explicit marker survives even when the event file is full.
            (self.directory / "events-truncated").write_text("Event size limit reached.\n")
            return None
        with self.path.open("ab", buffering=0) as handle:
            handle.write(encoded)
        if self.callback:
            self.callback(event)
        return event["event_id"]


def read_events(path):
    """A final torn line after a crash cannot discard earlier complete events."""
    path = Path(path)
    if not path.exists():
        return []
    if path.stat().st_size > 3 * 1024 * 1024:
        raise ValueError("Event stream exceeds limit")
    events = []
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            event = json.loads(line)
        except ValueError:
            break
        events.append(event)
    return events
